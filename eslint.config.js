/**
 * Frontend module boundaries: the TypeScript and Vue equivalent of deptrac.yaml.
 *
 * ESLint runs only this one rule. Everything else (style, correctness, type
 * aware checks) stays with Oxlint through `vp check`. Oxlint has no
 * equivalent of eslint-plugin-boundaries: `no-restricted-imports` can ban
 * paths but cannot say "a module may import its *own* internals and nobody
 * else's", which is the whole point.
 *
 * Every file under resources/js is sorted into one element type:
 *
 * | Type           | What                                                      |
 * |----------------|-----------------------------------------------------------|
 * | module         | modules/{key}/ plus its generated Wayfinder routes        |
 * |                | (routes/{key}). Its index.ts is the `entry` file: the     |
 * |                | module's only public surface. Everything else is internal |
 * | module-actions | Wayfinder controller helpers, actions/Modules/{Name}      |
 * | shared         | components, composables, lib, types, Core route helpers   |
 * |                | and the module registry                                   |
 * | core           | the app shell: app.ts, pages, layouts                     |
 *
 * And the policies, anything not listed is an error:
 *
 * | From   | May import                                                       |
 * |--------|------------------------------------------------------------------|
 * | module | shared, its own files and actions, another module's index.ts     |
 * | shared | shared                                                           |
 * | core   | core, shared                                                     |
 *
 * Core never imports a module: the registry finds modules with
 * import.meta.glob, which is not a static import, so Core's code holds no
 * module name. Same rule as the PHP side.
 *
 * Adding a module needs no change here. Keys are read from the folders in
 * resources/js/modules, and a module's PHP folder is its key in PascalCase
 * (kit-shop -> KitShop), which is how its generated actions are matched.
 *
 * Run with `make lint-js`; it also runs in the pre-commit hook and CI.
 */
import { readdirSync } from 'node:fs';
import boundaries from 'eslint-plugin-boundaries';
import tseslint from 'typescript-eslint';
import vueParser from 'vue-eslint-parser';

const MODULES = 'resources/js/modules';

const keys = readdirSync(MODULES, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);

const pascal = (key) =>
    key
        .split('-')
        .map((part) => part[0].toUpperCase() + part.slice(1))
        .join('');

// Extglob alternation: the matched key is captured like a `*` would be
const keyGlob = `@(${keys.join('|')})`;

export default [
    {
        ignores: [
            'vendor/**',
            'node_modules/**',
            'public/**',
            'bootstrap/ssr/**',
            // Generated by Wayfinder: classified below as import targets, but
            // not linted as sources
            'resources/js/actions/**',
            'resources/js/routes/**',
            'resources/js/wayfinder/**',
        ],
    },
    {
        files: ['resources/js/**/*.ts', 'resources/js/**/*.vue'],
        languageOptions: {
            parser: vueParser,
            parserOptions: {
                parser: tseslint.parser,
                extraFileExtensions: ['.vue'],
                sourceType: 'module',
            },
        },
        plugins: { boundaries },
        settings: {
            'import/resolver': {
                typescript: { alwaysTryTypes: true, project: 'tsconfig.json' },
            },
            'boundaries/include': ['resources/js/**/*'],
            // First match wins, so the specific patterns come first
            'boundaries/elements': [
                {
                    type: 'module',
                    pattern: `${MODULES}/*`,
                    partialMatch: false,
                    capture: ['key'],
                },
                // Wayfinder output for module routes and controllers. Generated
                // per module, so each belongs to the module that owns it
                {
                    type: 'module',
                    pattern: `resources/js/routes/${keyGlob}`,
                    partialMatch: false,
                    capture: ['key'],
                },
                {
                    type: 'module-actions',
                    pattern: 'resources/js/actions/Modules/*',
                    partialMatch: false,
                    capture: ['name'],
                },
                // What is left in actions/Modules is its index.ts, which
                // re-exports every module's controllers. Typed as core, which
                // modules cannot import, so it is no back door
                {
                    type: 'core',
                    pattern: 'resources/js/actions/Modules',
                    partialMatch: false,
                },
                {
                    type: 'shared',
                    pattern:
                        'resources/js/@(components|composables|lib|types|routes|actions|wayfinder)',
                    partialMatch: false,
                },
                {
                    type: 'core',
                    pattern: 'resources/js/@(pages|layouts)',
                    partialMatch: false,
                },
                // Elements are folders, so loose files are caught by their
                // parent once every folder above has had its turn: the
                // registry (modules/registry.ts) is shared, app.ts is core
                {
                    type: 'shared',
                    pattern: MODULES,
                    partialMatch: false,
                },
                {
                    type: 'core',
                    pattern: 'resources/js',
                    partialMatch: false,
                },
            ],
            // A module's public surface is one file inside the module element
            'boundaries/files': [
                { pattern: `${MODULES}/*/index.ts`, category: 'entry' },
            ],
            'boundaries/legacy-warnings': false,
        },
        rules: {
            'boundaries/no-unknown-files': 'error',
            'boundaries/dependencies': [
                'error',
                {
                    default: 'disallow',
                    checkAllOrigins: false,
                    message:
                        '{{ from.element.type }} {{ from.element.captured.key }} may not import {{ to.element.type }} {{ to.element.captured.key }}{{ to.element.captured.name }} ({{ to.file.path }}). See eslint.config.js for what each element may import.',
                    policies: [
                        {
                            from: { element: { type: 'module' } },
                            allow: [
                                { to: { element: { type: 'shared' } } },
                                // Its own internals, including its own index.ts
                                {
                                    to: {
                                        element: {
                                            type: 'module',
                                            captured: {
                                                key: '{{ from.element.captured.key }}',
                                            },
                                        },
                                    },
                                },
                                // Another module, through its index.ts only
                                {
                                    to: {
                                        element: { type: 'module' },
                                        file: { categories: 'entry' },
                                    },
                                },
                            ],
                        },
                        // Generated controller helpers are named after the PHP
                        // module folder, so they are matched by PascalCase name
                        ...keys.map((key) => ({
                            from: {
                                element: { type: 'module', captured: { key } },
                            },
                            allow: {
                                to: {
                                    element: {
                                        type: 'module-actions',
                                        captured: { name: pascal(key) },
                                    },
                                },
                            },
                        })),
                        {
                            from: { element: { type: 'shared' } },
                            allow: { to: { element: { type: 'shared' } } },
                        },
                        {
                            from: { element: { type: 'core' } },
                            allow: {
                                to: { element: { type: ['core', 'shared'] } },
                            },
                        },
                    ],
                },
            ],
        },
    },
];
